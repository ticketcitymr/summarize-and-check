"""Build docs/BEFORE_AFTER.md: for every example narrative, the original, the one-paragraph summary,
the check result and the completeness score. Re-run after any change to sar_summarizer.py:
    python make_report.py
"""
import argparse
import pathlib
import types

import sar_summarizer as S

ARGS = types.SimpleNamespace(engine="guided", words=130, model=None, nli=False, nli_model=None)
GROUPS = [("examples/sar_good", "Sufficient narratives (FinCEN guide examples)"),
          ("examples/sar_insufficient", "Insufficient narratives (FinCEN guide examples)")]

INTRO = """# Before and after: SAR narrative summaries

For each example narrative this page shows the **original (before)**, the **one-paragraph summary (after)**,
the **check** of the summary against the original, and the **completeness score** against FinCEN's
*Guidance on Preparing a Complete & Sufficient SAR Narrative* (Nov 2003).

All narratives are the public sample narratives printed in that guide. This page is generated by
`python make_report.py`; the summaries are produced by `sar_summarizer.py` with default settings
(extractive: every summary sentence is copied from the original, nothing is invented).

## How to read the results

| Item | Meaning |
|---|---|
| **Check: PASS / REVIEW / FAIL** | PASS = no red flags found. REVIEW = a person should look (for example the summary dropped the key amount or the subject). FAIL = something in the summary is not in the original (invented number or name) or a meaning flip. |
| **Summary keeps** | Whether the summary retained the subject, key amount, period, activity, follow-up action and the reason for suspicion. |
| **Completeness x/8** | Checklist of the guide's recommended elements found in the *original*: who, what, when, where, why, how, follow-up action, records location. 7-8 strong, 5-6 adequate, 0-4 thin. |

**Limits.** The check finds red flags, not truth; a PASS is not verification. Completeness is a keyword
checklist, not a regulatory determination, and can be wrong in both directions (see depository_2 under
the insufficient examples, which scores adequate although FinCEN rates it insufficient). Always read
the summary against the original.
"""


def md_quote(text):
    return "\n".join("> " + p if p.strip() else ">" for p in text.strip().split("\n"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="docs/BEFORE_AFTER.md")
    out = pathlib.Path(ap.parse_args().out)
    out.parent.mkdir(parents=True, exist_ok=True)
    lines, table = [INTRO], []
    body = []
    for folder, title in GROUPS:
        body.append(f"\n## {title}\n")
        for f in sorted(pathlib.Path(folder).glob("*.txt")):
            raw = f.read_text(encoding="utf-8")
            r = S.run_one(raw, ARGS)
            c = r["completeness"]
            kept = ", ".join(f"{lab} {'yes' if ok else '**NO**'}" for lab, ok, _ in r["kept"])
            table.append(f"| [{f.stem}](#{folder.split('_')[-1]}-{f.stem.replace('_', '-')}) | {folder.split('_')[-1]} "
                         f"| {r['narr_words']} | {r['sum_words']} | {r['overall']} | {c['score']}/8 ({c['label']}) |")
            body.append(f"### {folder.split('_')[-1]}-{f.stem.replace('_', '-')}\n")
            body.append(f"**Before** ({r['narr_words']} words)\n\n{md_quote(raw)}\n")
            body.append(f"**After** ({r['sum_words']} words)\n\n{md_quote(r['summary'])}\n")
            flagged = [f"- sentence {x['n']}: {x['verdict']} - " + "; ".join(x["issues"])
                       for x in r["results"] if x["verdict"] != "OK"]
            body.append(f"**Check: {r['overall']}.** Summary keeps: {kept}.")
            if flagged:
                body.append("\n" + "\n".join(flagged))
            for n in r["notes"]:
                body.append(f"\n- Note: {n}")
            body.append(f"\n**Completeness: {c['score']}/8 ({c['label']}).** "
                        + ", ".join(f"{lab} {'yes' if ok else '**NO**'}" for lab, ok in c["items"]) + ".")
            for w in c["warnings"]:
                body.append(f"\n- Warning: {w}")
            body.append("\n---\n")
    lines.append("## Overview\n\n| Example | Set | Original words | Summary words | Check | Completeness |\n|---|---|---|---|---|---|")
    lines.extend(table)
    lines.extend(body)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", out)


if __name__ == "__main__":
    main()
